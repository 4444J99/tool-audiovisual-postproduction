/** Write a network spec as files: the spec, a self-contained TouchDesigner build script, and the module sources. */
import {mkdirSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {buildNetworkSpec, validateNetworkSpec, pythonText} from './network-spec.mjs';

/** Deterministic JSON: the same patch and options always give the same bytes. */
export const serialise = value => `${JSON.stringify(value, null, 2)}\n`;

/** A JSON string literal is also a valid Python string literal, so the spec embeds without any second encoding. */
export function buildScript(spec) {
  const header = `# Generated by tools/fx-td-network.mjs from patch ${spec.patch.id}; do not edit, regenerate.
#
# In TouchDesigner's Textport:   exec(open("<this file>", encoding="utf-8").read(), {})
# To choose the parent, the media and a saved component first, put them in the dictionary:
#   exec(open("<this file>", encoding="utf-8").read(), {"FX_PARENT": "/project1", "FX_SAVE_TOX": "<path>.tox"})
# Under plain Python the script only defines SPEC, build() and run_in_touchdesigner(); it creates nothing.
`;
  const footer = `

SPEC = json.loads(${JSON.stringify(JSON.stringify(spec))})

try:
    import td as _td  # present only inside TouchDesigner
except ImportError:
    _td = None
if _td is not None and globals().get("FX_AUTOBUILD", True):
    RACK = run_in_touchdesigner(SPEC, globals().get("FX_PARENT", "/project1"), globals().get("FX_SAVE_TOX"))
    print("FX rack built at", RACK.path)
`;
  return header + pythonText('fx_td_build.py') + footer;
}

export function writeNetwork(patch, outDir, options = {}) {
  const spec = buildNetworkSpec(patch, options);
  const problems = validateNetworkSpec(spec);
  if (problems.length) throw Error(`Generated spec is not sound:\n${problems.join('\n')}`);
  mkdirSync(join(outDir, 'modules'), {recursive: true});
  const files = {
    [`${patch.id}.network.json`]: serialise(spec),
    [`${patch.id}.build.py`]: buildScript(spec),
    'modules/td_osc.py': pythonText('fx_td_osc.py'),
    'modules/osc_in_callbacks.py': pythonText('fx_td_osc_in_callbacks.py'),
    'modules/par_exec_nodes.py': pythonText('fx_td_par_exec_nodes.py'),
    'modules/par_exec_rack.py': pythonText('fx_td_par_exec_rack.py'),
  };
  for (const [name, text] of Object.entries(files)) writeFileSync(join(outDir, name), text);
  return {spec, files: Object.keys(files)};
}
